CREATE OR REPLACE PACKAGE BODY PKG_PERFIS_E_TRILHAS AS

    -- 1. Insert Usuario
    PROCEDURE PR_INSERIR_USUARIO (
        p_nome          IN USUARIO.NOME%TYPE,
        p_email         IN USUARIO.EMAIL%TYPE,
        p_senha_hash    IN USUARIO.SENHA_HASH%TYPE,
        p_id_usuario    OUT USUARIO.ID_USUARIO%TYPE
    ) AS
        v_id_perfil PERFIL.ID_PERFIL%TYPE;
    BEGIN
        INSERT INTO USUARIO (NOME, EMAIL, SENHA_HASH) VALUES (p_nome, p_email, p_senha_hash)
        RETURNING ID_USUARIO INTO p_id_usuario;
        INSERT INTO PERFIL (ID_USUARIO, TITULO_CARGO_ATUAL, DATA_ULTIMA_ATUALIZACAO) VALUES (p_id_usuario, 'Indefinido', SYSDATE)
        RETURNING ID_PERFIL INTO v_id_perfil;
    EXCEPTION
        WHEN OTHERS THEN RAISE_APPLICATION_ERROR(-20002, 'Erro ao inserir usuário: ' || SQLERRM);
    END PR_INSERIR_USUARIO;

    -- 2. Insert Skill
    PROCEDURE PR_INSERIR_SKILL (
        p_nome_skill    IN SKILL.NOME_SKILL%TYPE,
        p_tipo          IN SKILL.TIPO%TYPE,
        p_id_skill      OUT SKILL.ID_SKILL%TYPE
    ) AS
    BEGIN
        INSERT INTO SKILL (NOME_SKILL, TIPO) VALUES (p_nome_skill, p_tipo)
        RETURNING ID_SKILL INTO p_id_skill;
    EXCEPTION
        WHEN OTHERS THEN RAISE_APPLICATION_ERROR(-20011, 'Erro ao inserir skill: ' || SQLERRM);
    END PR_INSERIR_SKILL;

    -- 3. Add Skill Perfil
    PROCEDURE PR_ADICIONAR_SKILL_PERFIL (
        p_id_usuario    IN USUARIO.ID_USUARIO%TYPE,
        p_id_skill      IN SKILL.ID_SKILL%TYPE,
        p_nivel_dominio IN PERFIL_SKILL.NIVEL_DOMINIO%TYPE
    ) AS
        v_id_perfil PERFIL.ID_PERFIL%TYPE;
    BEGIN
        SELECT ID_PERFIL INTO v_id_perfil FROM PERFIL WHERE ID_USUARIO = p_id_usuario;
        INSERT INTO PERFIL_SKILL (ID_PERFIL, ID_SKILL, NIVEL_DOMINIO) VALUES (v_id_perfil, p_id_skill, p_nivel_dominio);
    EXCEPTION
        WHEN OTHERS THEN RAISE_APPLICATION_ERROR(-20014, 'Erro ao associar skill: ' || SQLERRM);
    END PR_ADICIONAR_SKILL_PERFIL;

    -- 4. Insert Trilha
    PROCEDURE PR_INSERIR_TRILHA (
        p_id_usuario      IN USUARIO.ID_USUARIO%TYPE,
        p_titulo_objetivo IN TRILHA_APRENDIZAGEM.TITULO_OBJETIVO%TYPE,
        p_id_trilha       OUT TRILHA_APRENDIZAGEM.ID_TRILHA%TYPE
    ) AS
        v_id_perfil PERFIL.ID_PERFIL%TYPE;
    BEGIN
        SELECT ID_PERFIL INTO v_id_perfil FROM PERFIL WHERE ID_USUARIO = p_id_usuario;
        INSERT INTO TRILHA_APRENDIZAGEM (ID_PERFIL, TITULO_OBJETIVO, STATUS) VALUES (v_id_perfil, p_titulo_objetivo, 'PENDENTE')
        RETURNING ID_TRILHA INTO p_id_trilha;
    EXCEPTION
        WHEN OTHERS THEN RAISE_APPLICATION_ERROR(-20016, 'Erro ao criar trilha: ' || SQLERRM);
    END PR_INSERIR_TRILHA;

    -- 5. Insert Etapa
    PROCEDURE PR_INSERIR_ETAPA_TRILHA (
        p_id_trilha     IN TRILHA_APRENDIZAGEM.ID_TRILHA%TYPE,
        p_ordem         IN ETAPA_TRILHA.ORDEM%TYPE,
        p_descricao     IN ETAPA_TRILHA.DESCRICAO%TYPE,
        p_tipo_recurso  IN ETAPA_TRILHA.TIPO_RECURSO%TYPE,
        p_id_etapa      OUT ETAPA_TRILHA.ID_ETAPA%TYPE
    ) AS
    BEGIN
        INSERT INTO ETAPA_TRILHA (ID_TRILHA, ORDEM, DESCRICAO, TIPO_RECURSO) VALUES (p_id_trilha, p_ordem, p_descricao, p_tipo_recurso)
        RETURNING ID_ETAPA INTO p_id_etapa;
    EXCEPTION
        WHEN OTHERS THEN RAISE_APPLICATION_ERROR(-20018, 'Erro ao inserir etapa: ' || SQLERRM);
    END PR_INSERIR_ETAPA_TRILHA;

    -- 6. Add Skill Etapa
    PROCEDURE PR_ADICIONAR_SKILL_ETAPA (p_id_etapa IN ETAPA_TRILHA.ID_ETAPA%TYPE, p_id_skill IN SKILL.ID_SKILL%TYPE) AS
    BEGIN
        INSERT INTO ETAPA_SKILL (ID_ETAPA, ID_SKILL) VALUES (p_id_etapa, p_id_skill);
    EXCEPTION
        WHEN OTHERS THEN RAISE_APPLICATION_ERROR(-20020, 'Erro ao associar skill/etapa: ' || SQLERRM);
    END PR_ADICIONAR_SKILL_ETAPA;

    -- === IMPLEMENTAÇÃO DO UPDATE ===
    PROCEDURE PR_ATUALIZAR_TRILHA (
        p_id_trilha       IN TRILHA_APRENDIZAGEM.ID_TRILHA%TYPE,
        p_titulo_objetivo IN TRILHA_APRENDIZAGEM.TITULO_OBJETIVO%TYPE
    ) AS
    BEGIN
        UPDATE TRILHA_APRENDIZAGEM
        SET TITULO_OBJETIVO = p_titulo_objetivo
        WHERE ID_TRILHA = p_id_trilha;

        IF SQL%ROWCOUNT = 0 THEN
            RAISE_APPLICATION_ERROR(-20025, 'Trilha não encontrada para atualização.');
        END IF;
    EXCEPTION
        WHEN OTHERS THEN RAISE_APPLICATION_ERROR(-20022, 'Erro ao atualizar trilha: ' || SQLERRM);
    END PR_ATUALIZAR_TRILHA;

    -- === IMPLEMENTAÇÃO DO DELETE (COM CASCADE MANUAL) ===
    PROCEDURE PR_DELETAR_TRILHA (
        p_id_trilha IN TRILHA_APRENDIZAGEM.ID_TRILHA%TYPE
    ) AS
    BEGIN
        -- Remove dependências em Etapa_Skill
        DELETE FROM ETAPA_SKILL WHERE ID_ETAPA IN (SELECT ID_ETAPA FROM ETAPA_TRILHA WHERE ID_TRILHA = p_id_trilha);
        -- Remove Etapas
        DELETE FROM ETAPA_TRILHA WHERE ID_TRILHA = p_id_trilha;
        -- Remove a Trilha
        DELETE FROM TRILHA_APRENDIZAGEM WHERE ID_TRILHA = p_id_trilha;

        IF SQL%ROWCOUNT = 0 THEN
            RAISE_APPLICATION_ERROR(-20026, 'Trilha não encontrada para exclusão.');
        END IF;
    EXCEPTION
        WHEN OTHERS THEN RAISE_APPLICATION_ERROR(-20024, 'Erro ao deletar trilha: ' || SQLERRM);
    END PR_DELETAR_TRILHA;


    -- 7. Função JSON Manual
    FUNCTION FN_PERFIL_TO_JSON_MANUAL (p_id_usuario IN USUARIO.ID_USUARIO%TYPE) RETURN CLOB AS
        v_json_result CLOB; v_nome USUARIO.NOME%TYPE; v_cargo PERFIL.TITULO_CARGO_ATUAL%TYPE;
        CURSOR c_skills IS SELECT s.NOME_SKILL, ps.NIVEL_DOMINIO FROM SKILL s JOIN PERFIL_SKILL ps ON s.ID_SKILL = ps.ID_SKILL JOIN PERFIL p ON ps.ID_PERFIL = p.ID_PERFIL WHERE p.ID_USUARIO = p_id_usuario;
        v_skill_array VARCHAR2(32767) := '['; v_count_skills NUMBER := 0;
    BEGIN
        SELECT u.NOME, p.TITULO_CARGO_ATUAL INTO v_nome, v_cargo FROM USUARIO u JOIN PERFIL p ON u.ID_USUARIO = p.ID_USUARIO WHERE u.ID_USUARIO = p_id_usuario;
        FOR r_skill IN c_skills LOOP
            IF v_count_skills > 0 THEN v_skill_array := v_skill_array || ','; END IF;
            v_skill_array := v_skill_array || '{"nome": "' || REPLACE(r_skill.NOME_SKILL, '"', '\"') || '", "nivel": ' || r_skill.NIVEL_DOMINIO || '}';
            v_count_skills := v_count_skills + 1;
        END LOOP;
        v_skill_array := v_skill_array || ']';
        v_json_result := '{"perfil": {"id": ' || p_id_usuario || ', "nome": "' || v_nome || '", "cargo": "' || NVL(v_cargo,'') || '"}, "skills": ' || v_skill_array || '}';
        RETURN v_json_result;
    EXCEPTION WHEN OTHERS THEN RETURN '{}';
    END FN_PERFIL_TO_JSON_MANUAL;

    -- 8. Função Cálculo Compatibilidade
    FUNCTION FN_CALC_COMPATIBILIDADE (p_id_perfil IN PERFIL.ID_PERFIL%TYPE, p_titulo_objetivo IN TRILHA_APRENDIZAGEM.TITULO_OBJETIVO%TYPE) RETURN CLOB AS
        v_email_usuario USUARIO.EMAIL%TYPE; v_compatibilidade NUMBER := 0; v_msg_retorno VARCHAR2(200);
        v_matched_count NUMBER := 0; v_total_required NUMBER := 5;
        c_required CONSTANT SYS.ODCIVARCHAR2LIST := SYS.ODCIVARCHAR2LIST('Kubernetes', 'AWS', 'Python', 'Git', 'Linux');
    BEGIN
        SELECT u.EMAIL INTO v_email_usuario FROM USUARIO u JOIN PERFIL p ON u.ID_USUARIO = p.ID_USUARIO WHERE p.ID_PERFIL = p_id_perfil;
        IF NOT REGEXP_LIKE(v_email_usuario, '^[a-zA-Z0-9._%+-]+@.+\.(com|org|net)$') THEN RAISE_APPLICATION_ERROR(-20006, 'Email inválido'); END IF;
        FOR i IN 1..v_total_required LOOP
            BEGIN
                SELECT 1 INTO v_matched_count FROM PERFIL_SKILL ps JOIN SKILL s ON ps.ID_SKILL = s.ID_SKILL WHERE ps.ID_PERFIL = p_id_perfil AND s.NOME_SKILL = c_required(i) AND ps.NIVEL_DOMINIO >= 3 AND ROWNUM = 1;
                v_compatibilidade := v_compatibilidade + (100/v_total_required);
            EXCEPTION WHEN NO_DATA_FOUND THEN NULL;
            END;
        END LOOP;
        RETURN '{"objetivo": "' || p_titulo_objetivo || '", "compatibilidade": ' || ROUND(v_compatibilidade) || '}';
    EXCEPTION WHEN OTHERS THEN RETURN '{"erro": "Erro no calculo"}';
    END FN_CALC_COMPATIBILIDADE;

    -- 9. PROCEDURE DE EXPORTAÇÃO PARA MONGODB
    PROCEDURE PR_EXPORTAR_DATASET_JSON (p_json_dataset OUT CLOB) AS
        v_json CLOB := '[';
        v_first_user BOOLEAN := TRUE;
        v_first_skill BOOLEAN;
        v_first_trilha BOOLEAN;

        CURSOR c_users IS SELECT U.ID_USUARIO, U.NOME, U.EMAIL, P.ID_PERFIL, P.TITULO_CARGO_ATUAL FROM USUARIO U JOIN PERFIL P ON U.ID_USUARIO = P.ID_USUARIO;
        CURSOR c_skills (p_perfil_id NUMBER) IS SELECT S.NOME_SKILL, PS.NIVEL_DOMINIO FROM PERFIL_SKILL PS JOIN SKILL S ON PS.ID_SKILL = S.ID_SKILL WHERE PS.ID_PERFIL = p_perfil_id;
        CURSOR c_trilhas (p_perfil_id NUMBER) IS SELECT T.TITULO_OBJETIVO, T.STATUS FROM TRILHA_APRENDIZAGEM T WHERE T.ID_PERFIL = p_perfil_id;
    BEGIN
        FOR r_u IN c_users LOOP
            IF NOT v_first_user THEN v_json := v_json || ','; END IF;
            v_first_user := FALSE;

            v_json := v_json || '{"_id": ' || r_u.ID_USUARIO || ', "nome": "' || r_u.NOME || '", "email": "' || r_u.EMAIL || '", "cargo": "' || r_u.TITULO_CARGO_ATUAL || '"';

            v_json := v_json || ', "habilidades": [';
            v_first_skill := TRUE;
            FOR r_s IN c_skills(r_u.ID_PERFIL) LOOP
                IF NOT v_first_skill THEN v_json := v_json || ','; END IF;
                v_json := v_json || '{"nome": "' || r_s.NOME_SKILL || '", "nivel": ' || r_s.NIVEL_DOMINIO || '}';
                v_first_skill := FALSE;
            END LOOP;
            v_json := v_json || ']';

            v_json := v_json || ', "trilhas": [';
            v_first_trilha := TRUE;
            FOR r_t IN c_trilhas(r_u.ID_PERFIL) LOOP
                IF NOT v_first_trilha THEN v_json := v_json || ','; END IF;
                v_json := v_json || '{"objetivo": "' || r_t.TITULO_OBJETIVO || '", "status": "' || r_t.STATUS || '"}';
                v_first_trilha := FALSE;
            END LOOP;
            v_json := v_json || ']}';

        END LOOP;
        v_json := v_json || ']';
        p_json_dataset := v_json;
    END PR_EXPORTAR_DATASET_JSON;

END PKG_PERFIS_E_TRILHAS;
