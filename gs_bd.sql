CREATE TABLE USUARIO (
    ID_USUARIO      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOME            VARCHAR2(100) NOT NULL,
    EMAIL           VARCHAR2(100) NOT NULL UNIQUE,
    SENHA_HASH      VARCHAR2(255) NOT NULL,
    DATA_CRIACAO    DATE DEFAULT SYSDATE
);

CREATE TABLE PERFIL (
    ID_PERFIL               NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_USUARIO              NUMBER NOT NULL UNIQUE,
    TITULO_CARGO_ATUAL      VARCHAR2(100),
    DATA_ULTIMA_ATUALIZACAO DATE,
    CONSTRAINT FK_PERFIL_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES USUARIO(ID_USUARIO)
);

CREATE TABLE SKILL (
    ID_SKILL        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOME_SKILL      VARCHAR2(100) NOT NULL UNIQUE,
    TIPO            VARCHAR2(20) NOT NULL CHECK (TIPO IN ('HARD', 'SOFT', 'COMPORTAMENTAL'))
);

CREATE TABLE PERFIL_SKILL (
    ID_PERFIL_SKILL NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_PERFIL       NUMBER NOT NULL,
    ID_SKILL        NUMBER NOT NULL,
    NIVEL_DOMINIO   NUMBER DEFAULT 1 CHECK (NIVEL_DOMINIO BETWEEN 1 AND 5),
    CONSTRAINT FK_PS_PERFIL FOREIGN KEY (ID_PERFIL) REFERENCES PERFIL(ID_PERFIL),
    CONSTRAINT FK_PS_SKILL FOREIGN KEY (ID_SKILL) REFERENCES SKILL(ID_SKILL),
    CONSTRAINT UK_PERFIL_SKILL UNIQUE (ID_PERFIL, ID_SKILL)
);

CREATE TABLE TRILHA_APRENDIZAGEM (
    ID_TRILHA               NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_PERFIL               NUMBER NOT NULL,
    TITULO_OBJETIVO         VARCHAR2(100) NOT NULL,
    DATA_GERACAO            DATE DEFAULT SYSDATE,
    STATUS                  VARCHAR2(20) DEFAULT 'PENDENTE' CHECK (STATUS IN ('PENDENTE', 'EM_PROGRESSO', 'CONCLUIDA', 'GERADA', 'ERRO')),
    DADOS_JSON_IA           CLOB, -- Campo para armazenar o JSON da IA
    CONSTRAINT FK_TRILHA_PERFIL FOREIGN KEY (ID_PERFIL) REFERENCES PERFIL(ID_PERFIL)
);

CREATE TABLE ETAPA_TRILHA (
    ID_ETAPA        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_TRILHA       NUMBER NOT NULL,
    ORDEM           NUMBER NOT NULL,
    DESCRICAO       VARCHAR2(500) NOT NULL,
    TIPO_RECURSO    VARCHAR2(50) NOT NULL,
    CONSTRAINT FK_ETAPA_TRILHA FOREIGN KEY (ID_TRILHA) REFERENCES TRILHA_APRENDIZAGEM(ID_TRILHA),
    CONSTRAINT UK_ETAPA_ORDEM UNIQUE (ID_TRILHA, ORDEM)
);

CREATE TABLE ETAPA_SKILL (
    ID_ETAPA_SKILL  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_ETAPA        NUMBER NOT NULL,
    ID_SKILL        NUMBER NOT NULL,
    CONSTRAINT FK_ES_ETAPA FOREIGN KEY (ID_ETAPA) REFERENCES ETAPA_TRILHA(ID_ETAPA),
    CONSTRAINT FK_ES_SKILL FOREIGN KEY (ID_SKILL) REFERENCES SKILL(ID_SKILL),
    CONSTRAINT UK_ETAPA_SKILL UNIQUE (ID_ETAPA, ID_SKILL)
);

CREATE TABLE LOG_AUDITORIA (
    ID_LOG              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOME_TABELA         VARCHAR2(50) NOT NULL,
    TIPO_OPERACAO       VARCHAR2(10) NOT NULL,
    DATA_OPERACAO       DATE DEFAULT SYSDATE,
    USUARIO_BD          VARCHAR2(50),
    DADOS_ANTERIORES    CLOB
);

--======================================================================
-- 3. TRIGGERS DE AUDITORIA
--======================================================================

CREATE OR REPLACE TRIGGER TRG_AUDIT_USUARIO
AFTER INSERT OR UPDATE OR DELETE ON USUARIO
FOR EACH ROW
DECLARE
    v_operacao LOG_AUDITORIA.TIPO_OPERACAO%TYPE;
    v_dados_anteriores CLOB;
BEGIN
    IF INSERTING THEN
        v_operacao := 'INSERT';
        v_dados_anteriores := NULL;
    ELSIF UPDATING THEN
        v_operacao := 'UPDATE';
        v_dados_anteriores := 'ID: ' || :OLD.ID_USUARIO || ', Nome Antigo: ' || :OLD.NOME || ', Email Antigo: ' || :OLD.EMAIL;
    ELSIF DELETING THEN
        v_operacao := 'DELETE';
        v_dados_anteriores := 'ID: ' || :OLD.ID_USUARIO || ', Nome: ' || :OLD.NOME || ', Email: ' || :OLD.EMAIL;
    END IF;

    INSERT INTO LOG_AUDITORIA (NOME_TABELA, TIPO_OPERACAO, USUARIO_BD, DADOS_ANTERIORES)
    VALUES ('USUARIO', v_operacao, USER, v_dados_anteriores);
END;
